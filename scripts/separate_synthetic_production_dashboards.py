        if p.get("id") == 14:
            p["title"] = "Recent Captured Enterprise SIP Call Transactions [PRODUCTION — CARRIER & AVAYA TRUNKS]"
            p["description"] = "Real-time captured SIP call transactions from corporate Avaya SBC and carrier trunks, excluding synthetic loopback probes."
            for t in p.get("targets", []):
                t["rawSql"] = "SELECT create_date AS \"time\", sid AS \"call_id\", protocol_header->>'srcIp' AS \"source_ip\", protocol_header->>'srcPort' AS \"src_port\", protocol_header->>'dstIp' AS \"dest_ip\", protocol_header->>'dstPort' AS \"dst_port\", data_header->>'method' AS \"method\" FROM hep_proto_1_call WHERE (COALESCE(protocol_header->>'captureId', '') != 'nawari-avtest-lab' AND protocol_header->>'srcIp' NOT IN ('127.0.0.1', '::1')) ORDER BY create_date DESC LIMIT 50;"
