def update_voice_service_assurance():
    path = Path("communication-observability/docker/grafana/dashboards/communication_observability/nawari-voice-service-assurance.json")
    with open(path, "r") as f:
        d = json.load(f)

    panels = d.get("panels", [])
    for p in panels:
        if p.get("id") == 14:
            p["title"] = "Recent Synthetic Call Traces [SYNTHETIC — ASTERISK PROBE]"
            for t in p.get("targets", []):
                t["rawSql"] = "SELECT create_date AS \"time\", sid AS \"call_id\", protocol_header->>'srcIp' AS \"source\", protocol_header->>'dstIp' AS \"destination\", data_header->>'method' AS \"method\" FROM hep_proto_1_call WHERE protocol_header->>'captureId' = 'nawari-avtest-lab' OR protocol_header->>'srcIp' IN ('127.0.0.1', '::1') ORDER BY create_date DESC LIMIT 25;"

    d["panels"] = panels
    with open(path, "w") as f:
        json.dump(d, f, indent=2)
    print("Updated nawari-voice-service-assurance.json")


if __name__ == "__main__":
    update_voice_intelligence()
    update_sip_trunks()
    update_voice_service_assurance()
