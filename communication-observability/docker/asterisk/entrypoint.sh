#!/bin/bash
set -euo pipefail

log() {
    echo "[NAWARI-ASTERISK] $(date '+%Y-%m-%d %H:%M:%S') - $*"
}

log "Initializing Nawari Asterisk 22 container..."

# Ensure runtime directories exist with correct ownership
mkdir -p /var/run/asterisk /var/log/asterisk /var/spool/asterisk /var/lib/asterisk /etc/asterisk
chown -R asterisk:asterisk /var/run/asterisk /var/log/asterisk /var/spool/asterisk /var/lib/asterisk

# Render manager.conf with dynamic AMI secret
AMI_SECRET="${ASTERISK_AMI_SECRET:-nawari_ami_secret_dev}"
cat << EOF > /etc/asterisk/manager.conf
; NAWARI AMI Configuration
; Auto-generated by entrypoint.sh

[general]
enabled = yes
webenabled = no
port = 5038
bindaddr = 0.0.0.0
allowmultiplelogin = yes
displayconnects = yes

[nawari]
secret = ${AMI_SECRET}
read = all
write = all
EOF
chown asterisk:asterisk /etc/asterisk/manager.conf
chmod 640 /etc/asterisk/manager.conf

log "AMI configured for user 'nawari' on port 5038"

# Fix permissions on /etc/asterisk
chown -R asterisk:asterisk /etc/asterisk

log "Starting Asterisk in foreground..."
exec /usr/sbin/asterisk -f -U asterisk -G asterisk

