def update_sip_trunks():
    path = COMM_DIR / "nawari_sip_trunks_signaling.json"
    with open(path) as f:
        d = json.load(f)

    for p in d.get("panels", []):
        pid = p.get("id")
        for t in p.get("targets", []):
            h = t.get("host")
            if pid in (2, 3, 4):
                # Carrier SIP trunks
                if isinstance(h, dict):
                    h["name"] = "sip-trunk-carrier-01"
                else:
                    t["host"] = "sip-trunk-carrier-01"
                it = t.get("item", {})
                if isinstance(it, dict):
                    if it.get("name") == "Safaricom Primary SIP Trunk Operational Status":
                        it["name"] = "SIP Trunk Endpoint Reachability"
                    elif it.get("name") == "Airtel Secondary SIP Trunk Operational Status":
                        it["name"] = "SIP Trunk OPTIONS Probe Status"
                    elif "Latency" in it.get("name", ""):
                        it["name"] = "SIP Trunk OPTIONS Response Time"
            elif pid in (9, 10):
                # SBCE perimeter interfaces
                if isinstance(h, dict):
                    h["name"] = "avaya-sbce-01"
                else:
                    t["host"] = "avaya-sbce-01"
                it = t.get("item", {})
                if isinstance(it, dict):
                    if it.get("name") == "Voice Path Packet Errors (rate)":
                        it["name"] = "SBCE Aggregate Interface Error Rate"

    with open(path, "w") as f:
        json.dump(d, f, indent=2)
    print("Updated nawari_sip_trunks_signaling.json")


def update_root_symlinks():
    for f in COMM_DIR.glob("*.json"):
        symlink = ROOT_DASH_DIR / f.name
        if symlink.exists() or symlink.is_symlink():
            symlink.unlink()
        symlink.symlink_to(f"communication_observability/{f.name}")
        print(f"Symlinked {f.name} -> communication_observability/{f.name}")


