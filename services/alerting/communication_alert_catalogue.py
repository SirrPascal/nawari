from __future__ import annotations

from typing import Any, Dict, List
from services.alerting.models import AlertEvidence, AlertRule, AlertSeverity


def _eval_gt(threshold: float):
    return lambda val, ctx: val is not None and float(val) > threshold


def _eval_gte(threshold: float):
    return lambda val, ctx: val is not None and float(val) >= threshold


def _eval_eq(target: Any):
    return lambda val, ctx: val is not None and val == target


def _eval_neq(target: Any):
    return lambda val, ctx: val is not None and val != target


def _eval_bool_false(val: Any, ctx: Dict[str, Any]) -> bool:
    return val is not None and (val is False or val == 0 or val == "0" or str(val).upper() in ("DOWN", "OFFLINE"))


def _eval_bool_true(val: Any, ctx: Dict[str, Any]) -> bool:
    return val is not None and (val is True or val == 1 or val == "1" or str(val).upper() in ("UP", "ONLINE"))


